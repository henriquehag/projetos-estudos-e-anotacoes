dia = input("Digite o dia da semana: ")

if dia == "segunda":
    
    print("Hoje é segunda-feira.")
    
    
elif dia == "terça": print("Hoje é terça-feira.")

elif dia == "quarta": print("Hoje é quarta-feira.")
    
elif dia == "quinta": print("Hoje é quinta-feira.")

elif dia == "sexta": print("Hoje é sexta-feira.")
elif dia == "sábado": print("Hoje é sábado.")
elif dia == "domingo": print("Hoje é domingo.")
else: print("Dia inválido.")